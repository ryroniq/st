/*
 * Special keys (change & recompile st.info accordingly)
 *
 * Mask value:
 * * Use XK_ANY_MOD to match the key no matter modifiers state
 * * Use XK_NO_MOD to match the key alone (no modifiers)
 * appkey value:
 * * 0: no value
 * * > 0: keypad application mode enabled
 * *   = 2: term.numlock = 1
 * * < 0: keypad application mode disabled
 * appcursor value:
 * * 0: no value
 * * > 0: cursor application mode enabled
 * * < 0: cursor application mode disabled
 *
 * Be careful with the order of the definitions because st searches in
 * this table sequentially, so any XK_ANY_MOD must be in the last
 * position for a key.
 *
 * Cursor, editing and F1-F12 keys pressed with Shift, Alt, Ctrl or Super
 * (Mod4) never reach this table; they are sent in xterm's format, e.g.
 * "\033[1;5A" or "\033[3;2~".  When an application enables xterm's
 * modifyOtherKeys (CSI > 4 ; 1 m or CSI > 4 ; 2 m), modified printable,
 * Return, Tab, BackSpace and Escape keys are sent as "\033[<code>;<mod>u"
 * before this table is searched as well.
 */

